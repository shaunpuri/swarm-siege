// Copies the ChatGPT world maps that are ready (all five biomes painted for a layout) into
// src/assets/worlds as JPEGs (plus small thumbnails in src/assets/thumbs for the campaign
// screens), and writes src/three/worldart.ts importing them, so the game only ever
// references maps that exist. Run with: bun scripts/world-art.ts

import { existsSync, mkdirSync } from "node:fs";

const ROOT = `${import.meta.dir}/..`;
const SRC = `${ROOT}/art/source/chatgpt`;
const OUT = `${ROOT}/src/assets/worlds`;
const THUMBS = `${ROOT}/src/assets/thumbs`;
const BIOMES = ["grassland", "snow", "desert", "water", "cyber"];

mkdirSync(OUT, { recursive: true });
mkdirSync(THUMBS, { recursive: true });
const ready: number[] = [];
for (let i = 1; i <= 10; i++) {
  if (!BIOMES.every((b) => existsSync(`${SRC}/${b}-${i}.png`))) continue;
  for (const b of BIOMES) {
    const proc = Bun.spawnSync(["convert", `${SRC}/${b}-${i}.png`, "-quality", "88", `${OUT}/${b}-${i}.jpg`]);
    if (proc.exitCode !== 0) throw new Error(proc.stderr.toString());
    const thumb = Bun.spawnSync(["convert", `${SRC}/${b}-${i}.png`, "-resize", "480x270", "-quality", "82", `${THUMBS}/${b}-${i}.jpg`]);
    if (thumb.exitCode !== 0) throw new Error(thumb.stderr.toString());
  }
  ready.push(i);
}

// base sprites keyed out of ChatGPT's green-screen redraws (scripts/extract-gpt.ts), if made yet
const BASE_SETS = ["snow", "aqua", "desert", "cyber", "forest"];
const bases = BASE_SETS.map((set) => ({ set, levels: [1, 2, 3].filter((l) => existsSync(`${ROOT}/src/assets/sprites/bases/${set}-${l}.png`)) }));

const lines = [
  "// Generated by scripts/world-art.ts: the world maps that have all five biomes painted, and",
  "// the base sprites for each upgrade level that exist so far.",
  'import type { Biome } from "@/types";',
  "",
  ...ready.flatMap((i) => BIOMES.map((b) => `import ${b}${i} from "@/assets/worlds/${b}-${i}.jpg";`)),
  "",
  "export const WORLD_ART: Record<number, Record<Biome, string>> = {",
  ...ready.map((i) => `  ${i}: { ${BIOMES.map((b) => `${b}: ${b}${i}`).join(", ")} },`),
  "};",
  "",
  ...ready.flatMap((i) => BIOMES.map((b) => `import ${b}Thumb${i} from "@/assets/thumbs/${b}-${i}.jpg";`)),
  "// 480x270 previews for the campaign screens",
  "export const WORLD_THUMBS: Record<number, Record<Biome, string>> = {",
  ...ready.map((i) => `  ${i}: { ${BIOMES.map((b) => `${b}: ${b}Thumb${i}`).join(", ")} },`),
  "};",
  "",
  ...bases.flatMap((b) => b.levels.map((l) => `import ${b.set}Base${l} from "@/assets/sprites/bases/${b.set}-${l}.png";`)),
  "// base sprites per upgrade level: Cold World ice fortress, Aqua World ocean palace, Desert temple, Cyber Arena nexus, Forest sanctuary",
  `export const BASE_ART: Record<string, string[]> = { ${bases.map((b) => `${b.set}: [${b.levels.map((l) => `${b.set}Base${l}`).join(", ")}]`).join(", ")} };`,
  "",
];
await Bun.write(`${ROOT}/src/three/worldart.ts`, lines.join("\n"));
console.log(`world maps ready: ${ready.join(", ") || "none"}`);
