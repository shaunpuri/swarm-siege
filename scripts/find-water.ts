// Finds where the anaconda rises out of the river on each Grassland world map (the Night
// Anaconda sheet: it emerges from the river, slides up the bank and onto the road). For every
// route it looks at the painted map for open water beside the road, along the first part of
// the route, and keeps the riverbank spot nearest the entrance. Writes src/config/riverspots.ts.
// Run with: bun scripts/find-water.ts

import { WORLD_MAPS } from "@/config/worldmaps";

const ROOT = `${import.meta.dir}/..`;
const W = 1672;
const H = 941;
// the map is read at a quarter size (plenty to find a river)
const STEP = 4;
const w = Math.floor(W / STEP);
const h = Math.floor(H / STEP);

type P = [number, number];

function pixels(path: string): Uint8Array {
  const out = Bun.spawnSync(["convert", path, "-resize", `${w}x${h}!`, "-depth", "8", "rgb:-"], { stdout: "pipe" });
  if (out.exitCode !== 0) throw new Error(`could not read ${path}`);
  return new Uint8Array(out.stdout);
}

// the painted rivers are a clear cyan blue
function isWater(px: Uint8Array, x: number, y: number): boolean {
  const i = (y * w + x) * 3;
  const r = px[i] ?? 0;
  const g = px[i + 1] ?? 0;
  const b = px[i + 2] ?? 0;
  // cyan, not the portals' deep blue and purple
  return b > 120 && b > r + 45 && g > r + 35 && g > b * 0.78;
}

// open water: most of the area round the point is river (not a thin glowing road edge)
function openWater(px: Uint8Array, x: number, y: number): boolean {
  let n = 0;
  let wet = 0;
  for (let dy = -3; dy <= 3; dy++) {
    for (let dx = -3; dx <= 3; dx++) {
      const xx = x + dx;
      const yy = y + dy;
      if (xx < 0 || yy < 0 || xx >= w || yy >= h) continue;
      n += 1;
      if (isWater(px, xx, yy)) wet += 1;
    }
  }
  return n > 0 && wet / n > 0.75;
}

function dist(a: P, b: P): number {
  return Math.hypot(a[0] - b[0], a[1] - b[1]);
}

// the nearest point of the route to p: how far it is, and how far along the route (0..1)
function nearest(route: P[], p: P): { d: number; along: number } {
  const lengths: number[] = [];
  let total = 0;
  for (let i = 1; i < route.length; i++) {
    const a = route[i - 1];
    const b = route[i];
    if (!a || !b) continue;
    lengths.push(dist(a, b));
    total += dist(a, b);
  }
  let best = { d: Infinity, along: 0 };
  let walked = 0;
  for (let i = 1; i < route.length; i++) {
    const a = route[i - 1];
    const b = route[i];
    const len = lengths[i - 1] ?? 0;
    if (!a || !b) continue;
    const t = len === 0 ? 0 : Math.max(0, Math.min(1, ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1])) / (len * len)));
    const q: P = [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
    const d = dist(p, q);
    if (d < best.d) best = { d, along: (walked + len * t) / total };
    walked += len;
  }
  return best;
}

// a river spot for one route: open water 35..120 map pixels from the road, clear of the
// turret pads and the entrance, on the first 70% of the route; the earliest one wins
function spotFor(px: Uint8Array, route: P[], pads: P[], portals: P[]): { water: P; along: number } | null {
  let best: { water: P; along: number } | null = null;
  const entrance = route[0];
  for (let y = 4; y < h - 4; y++) {
    for (let x = 4; x < w - 4; x++) {
      if (!openWater(px, x, y)) continue;
      const p: P = [x * STEP, y * STEP];
      if (entrance && dist(p, entrance) < 120) continue;
      if (pads.some((pad) => dist(p, pad) < 70)) continue;
      if (portals.some((q) => dist(p, q) < 110)) continue;
      const near = nearest(route, p);
      if (near.d < 35 || near.d > 120 || near.along < 0.06 || near.along > 0.7) continue;
      if (!best || near.along < best.along) best = { water: p, along: near.along };
    }
  }
  return best;
}

const lines: string[] = [];
for (const [id, spec] of Object.entries(WORLD_MAPS)) {
  const px = pixels(`${ROOT}/src/assets/worlds/grassland-${id}.jpg`);
  // both ends of every portal jump, on every route
  const portals: P[] = spec.routes.flatMap((route, r) => (spec.jumps[r] ?? []).flatMap((i) => [route[i], route[i + 1]].filter((q): q is P => q !== undefined)));
  const spots = spec.routes.map((route) => spotFor(px, route, spec.pads, portals));
  const text = spots.map((s) => (s ? `{ water: [${s.water[0]}, ${s.water[1]}], along: ${s.along.toFixed(3)} }` : "null")).join(", ");
  lines.push(`  ${id}: [${text}],`);
  console.log(`level ${id}: ${spots.map((s) => (s ? `water at ${s.water.join(",")} joins at ${Math.round(s.along * 100)}%` : "no river")).join(" | ")}`);
}

const out = `// Generated by scripts/find-water.ts from the Grassland world maps. Do not edit by hand.
// Where the anaconda rises out of the river on each level, per route: the river spot (map
// pixels, 1672x941) and how far along the route (0..1) it reaches the road. null: no river
// beside that route, so it emerges at the entrance as before.

export type RiverSpot = { water: [number, number]; along: number };

export const RIVER_SPOTS: Record<number, (RiverSpot | null)[]> = {
${lines.join("\n")}
};
`;
await Bun.write(`${ROOT}/src/config/riverspots.ts`, out);
