// Writes src/three/modelart.ts, importing every web-ready 3D model in src/assets/models
// (made by scripts/tripo.ts): turrets <biome>-tower-<level>, bases <biome>-base-<level>,
// enemies <biome>-<kind>. Run with: bun scripts/models.ts

import { readdirSync } from "node:fs";

const ROOT = `${import.meta.dir}/..`;
const files = readdirSync(`${ROOT}/src/assets/models`).filter((f) => f.endsWith(".glb")).sort();

type Entry = { id: string; key: string; file: string };

function group(re: RegExp, key: (m: RegExpMatchArray) => string): Entry[] {
  return files.flatMap((file) => {
    const m = file.match(re);
    return m ? [{ id: file.replace(".glb", "").replace(/-(\w)/g, (_, c: string) => c.toUpperCase()), key: key(m), file }] : [];
  });
}

const towers = group(/^([a-z]+)-tower-(\d)\.glb$/, (m) => `${m[1]}-${m[2]}`);
const bases = group(/^([a-z]+)-base-(\d)\.glb$/, (m) => `${m[1]}-${m[2]}`);
const enemies = group(/^([a-z]+)-(scout|brute|overlord|titan)\.glb$/, (m) => `${m[1]}-${m[2]}`);
const record = (name: string, list: Entry[]): string => `export const ${name}: Record<string, string> = { ${list.map((e) => `"${e.key}": ${e.id}`).join(", ")} };`;

const lines = [
  "// Generated by scripts/models.ts: the 3D models that exist so far, keyed biome-level or biome-kind.",
  ...[...towers, ...bases, ...enemies].map((e) => `import ${e.id} from "@/assets/models/${e.file}";`),
  "",
  record("TOWER_MODELS", towers),
  record("BASE_MODELS", bases),
  record("ENEMY_MODELS", enemies),
  "",
];
await Bun.write(`${ROOT}/src/three/modelart.ts`, lines.join("\n"));
console.log(`registered ${towers.length} turrets, ${bases.length} bases, ${enemies.length} enemies`);
