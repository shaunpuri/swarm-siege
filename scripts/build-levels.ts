const ROOT = `${import.meta.dir}/..`;
const DEBUG = process.env["TRACE_DEBUG"] ?? "/tmp";

function trace(level: number, stops: P[], tag: string): P[] {
  const proc = Bun.spawnSync(["bun", `${ROOT}/scripts/trace-road.ts`, `${ROOT}/art/source/maps/level-${level}.png`, `${DEBUG}/l${level}-${tag}`, stops.map((s) => s.join(",")).join(" ")], { stdout: "pipe", stderr: "pipe" });
  if (proc.exitCode !== 0) throw new Error(`level ${level} ${tag}: ${proc.stderr.toString()}`);
  const parsed: unknown = JSON.parse(proc.stdout.toString());
  if (!Array.isArray(parsed)) throw new Error("bad trace output");
  return parsed.map((pt): P => {
    if (!Array.isArray(pt)) throw new Error("bad point");
    return [Number(pt[0]), Number(pt[1])];
  });
}

const fmt = (p: P): string => `[${p[0]}, ${p[1]}]`;
