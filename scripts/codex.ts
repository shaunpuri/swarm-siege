// Builds the Codex art: the 3D model preview renders from Tripo (art/models/*.webp, 512px)
// shrunk to 256px webp in src/assets/codex, and src/config/codexart.ts mapping each model name
// (e.g. "snow-titan", "desert-tower-2", "water-base-1") to its image.
// Run with: bun scripts/codex.ts

import { mkdirSync, readdirSync } from "node:fs";

const ROOT = `${import.meta.dir}/..`;
const OUT = `${ROOT}/src/assets/codex`;
mkdirSync(OUT, { recursive: true });
const names = readdirSync(`${ROOT}/art/models`)
  .filter((f) => f.endsWith(".webp"))
  .map((f) => f.slice(0, -5))
  .sort();
for (const name of names) {
  const r = Bun.spawnSync(["convert", `${ROOT}/art/models/${name}.webp`, "-resize", "256x256", "-quality", "82", `${OUT}/${name}.webp`]);
  if (r.exitCode !== 0) throw new Error(`could not convert ${name}`);
}
const ident = (n: string): string => n.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const lines = names.map((n) => `import ${ident(n)} from "@/assets/codex/${n}.webp";`);
const out = `// Generated by scripts/codex.ts. Do not edit by hand.
${lines.join("\n")}

export const CODEX_ART: Record<string, string> = { ${names.map((n) => `"${n}": ${ident(n)}`).join(", ")} };
`;
await Bun.write(`${ROOT}/src/config/codexart.ts`, out);
console.log(`codex: ${names.length} images`);
